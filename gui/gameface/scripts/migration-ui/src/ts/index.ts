import { Console, Context, Effect, Layer } from 'effect'
import path from 'path'

import { FSE } from '../bindings'
import { Dirty } from '../core'
import { BUNNER } from '../core/banner'
import { countDepth } from '../utils/strings'

export class TsContext extends Context.Tag('@/TsContext')<
    TsContext,
    {
        readonly renamedCss: Set<string>
    }
>() {}

function saveFile(filepath: string) {
    return (content: Dirty<string>) => {
        if (!content.dirty) {
            return Effect.succeed(undefined)
        }
        return FSE.writeFile(filepath, content.value).pipe(
            Effect.withSpan(`Write file: ${filepath}`),
        )
    }
}

function addBanner(content: Dirty<string>): Dirty<string> {
    if (content.value.includes('WARN: file has been generated by gameface/scripts/migration-cli tool')) {
        return content;
    }

    return {
        ...content,
        value: `${BUNNER}\n${content.value}`,
        dirty: true
    };
}

function updateUseMedia(content: Dirty<string>) {
    return Dirty.update(content, (value) => {
        const hasMediaUsage = value.match(/from\s+'lib\/hooks\/useMedia'/g)

        if (!hasMediaUsage) {
            return value
        }

        return value
            .replace(
                /import\s+{([^}]+)}\s+from\s+'lib\/hooks\/useMedia';/g,
                "import { useMedia } from '@wg/media_wrapper';\nimport { breakpointsByType } from '@wg/media_wrapper/static';",
            )
            .replace('const { mediaSize } = useMedia()', 'const { breakpoint: {weight: mediaSize} } = useMedia()')
            .replace(/MediaSize\.(ExtraSmall|Small|Medium|Large|ExtraLarge)/g, (match, p1) => {
                const lowerCaseName = p1.charAt(0).toLowerCase() + p1.slice(1)
                return `breakpointsByType.${lowerCaseName}.weight`
            })
    })
}

function updateViewEnvHelper(filepath: string) {
    return (content: Dirty<string>) => {
        const depth = countDepth('components', filepath)
        const up = '../'.repeat(depth)
        return Dirty.update(content, (value) => {
            return value.replace(/import\s+{([^}]+)}\s+from\s+'lib\/view\-env\-helper/g, (match, elements) => {
                return `import {${elements}} from '${up}lib/view-env-helper`
            })
        })
    }
}

const gfRoot = '../../../src/'
function updateLib(filepath: string) {
    return (content: Dirty<string>) => {
        const depth = countDepth('legacy/components', filepath)
        const up = '../'.repeat(depth) + gfRoot
        return Dirty.update(content, (value) => {
            return value
                .replace(/import\s+{([^}]+)}\s+from\s+'(?:\.{1,2}\/)*lib\//g, (match, elements) => {
                    return `import {${elements}} from '${up}lib/`
                })
                .replace(/import\s+([a-zA-Z_$][a-zA-Z0-9_$]*)\s+from\s+'(?:\.{1,2}\/)*lib\//g, (match, element) => {
                    return `import ${element} from '${up}lib/`
                })
        })
    }
}

function updateForwardRef(content: Dirty<string>) {
    return Dirty.update(content, (value) => {
        return value.replaceAll('RefForwardingComponent', 'ForwardRefRenderFunction')
    })
}

function updateComponents(filepath: string) {
    return (content: Dirty<string>) => {
        const depth = countDepth('legacy/components', filepath)
        const up = '../'.repeat(depth)
        return Dirty.update(content, (value) => {
            return value.replace(/import\s+{([^}]+)}\s+from\s+'components\//g, (match, elements) => {
                filepath.includes('Wait') && console.log(`found ${filepath} ${up}components`)
                return `import {${elements}} from '${up}components/`
            })
        })
    }
}

function updateReactSpring(content: Dirty<string>) {
    return Dirty.update(content, (value) => {
        return value.replace(`from 'react-spring'`, (match) => {
            return `from '@react-spring/web'`
        })
    })
}

function warnUnsupported(filepath: string) {
    return (content: Dirty<string>) => {
        return Effect.gen(function* (_) {
            if (/(mediaWidth|mediaHeight|remScreenWidth|remScreenHeight)/g.test(content.value)) {
                yield* Console.warn(
                    `⚠️  Unsupported use of hook found in ${filepath}: mediaWidth|mediaHeight|remScreenWidth|remScreenHeight from useMedia()`,
                )
            }
            if (content.value.includes('useModel<')) {
                yield* Console.warn(`⚠️  Unsupported hook found in ${filepath}: deprecated useModel`)
            }
            return content
        })
    }
}

function mergeImports(content: Dirty<string>) {
    if (!content.dirty) {
        return content
    }
    return Dirty.update(content, (value) => {
        const importRegex = /import\s+{([^}]+)}\s+from\s+['"]([^'"]+)['"];?/g

        const importsMap: { [key: string]: Set<string> } = {}

        let match: RegExpExecArray | null
        let index = 0
        const ranges: { start: number; end: number }[] = []

        while ((match = importRegex.exec(value)) !== null) {
            const start = match.index
            const end = start + match[0].length
            ranges.push({ start, end })
            const identifiers = match[1].split(',').map((id) => id.trim())
            const module = match[2]

            if (!importsMap[module]) {
                importsMap[module] = new Set<string>()
            }

            identifiers.forEach((id) => importsMap[module].add(id))
            index++
        }

        const mergedImports = Object.entries(importsMap).map(([module, ids]) => {
            const identifiers = Array.from(ids).join(', ')
            return `import { ${identifiers} } from '${module}';`
        })

        // Remove old imports
        const newContent = ranges.reduceRight((acc, { start, end }) => {
            return acc.slice(0, start) + acc.slice(end)
        }, value)

        // Concat merged imports with content
        return mergedImports.join('\n') + '\n' + newContent
    })
}

function updateCssImports(filepath: string) {
    return (content: Dirty<string>) => {
        const css = {
            module: new Set<string>(),
        }
        const newContent = Dirty.update(content, (value) => {
            const namedImportRegex = /import\s+(\w+)\s+from\s+['"]\.\/(\w+)\.css['"];/g
            const unnamedImportRegex = /import\s+['"]\.\/(\w+)\.css['"];/g

            return value
                .replace(namedImportRegex, (match, styles, fileName) => {
                    css.module.add(fileName)
                    return `import ${styles} from './${fileName}.module.scss';`
                })
                .replace(unnamedImportRegex, (match, fileName) => {
                    return `import './${fileName}.scss';`
                })
        })
        return Effect.gen(function* (_) {
            const ctx = yield* TsContext
            yield* Effect.all(
                Array.from(css.module.values()).map((filename) => {
                    const scssPath = path.resolve(path.dirname(filepath), `${filename}.scss`)
                    if (ctx.renamedCss.has(scssPath)) {
                        return Effect.succeed(undefined)
                    }
                    return FSE.rename(scssPath, path.resolve(path.dirname(filepath), `${filename}.module.scss`)).pipe(
                        Effect.tap(() => ctx.renamedCss.add(scssPath)),
                    )
                }),
            ).pipe(Effect.withSpan('Rename CSS files'))
            return newContent
        })
    }
}

function processFile(filepath: string) {
    return FSE.readFile(filepath).pipe(
        Effect.withSpan(`Read file: ${filepath}`),
        Effect.map(String),
        Effect.map(Dirty.of),
        Effect.map(updateUseMedia),
        Effect.andThen(updateLib(filepath)),
        Effect.andThen(updateComponents(filepath)),
        Effect.map(updateReactSpring),
        Effect.map(updateForwardRef),
        Effect.map(mergeImports),
        Effect.andThen(warnUnsupported(filepath)),
        Effect.andThen(updateCssImports(filepath)),
        Effect.map(addBanner),
        Effect.andThen(saveFile(filepath)),
    )
}

export function tsProcess(folder: string) {
    const context = Layer.succeed(TsContext, TsContext.of({ renamedCss: new Set() }))
    return Effect.gen(function* (_) {
        const files = yield* FSE.glob(FSE.convertPathToPattern(`${folder}`) + '/**/*.{ts,tsx}', {
            absolute: true,
        }).pipe(Effect.withSpan('Glob TS files'))
        yield* Console.log(`Found ${files.length} TS files`)
        yield* Effect.all(files.map(processFile)).pipe(Effect.withSpan('Process TS files'))
    }).pipe(Effect.provide(context))
}
